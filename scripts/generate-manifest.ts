import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/**
 * 从 src/routes 源码直接生成 Hono 404 白名单，避免依赖 vite 构建时才更新的
 * routeTree.gen.ts（此前 build 先读旧 routeTree，新增路由会漏进白名单）。
 */

const routesDir = path.join(process.cwd(), "src/routes");
const outputPath = path.join(
  process.cwd(),
  "src/lib/hono/path-manifest.generated.ts",
);

function walk(directory: string): Array<string> {
  const files: Array<string> = [];
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...walk(fullPath));
    } else if (entry.isFile() && entry.name.endsWith(".tsx")) {
      files.push(fullPath);
    }
  }
  return files;
}

function isRouteFile(filePath: string): boolean {
  const baseName = path.basename(filePath, ".tsx");
  return baseName !== "__root" && baseName !== "route";
}

export function collectRoutePaths(routeRoot: string): Array<string> {
  const paths = new Set<string>();

  for (const filePath of walk(routeRoot)) {
    if (!isRouteFile(filePath)) continue;

    const relative = path
      .relative(routeRoot, filePath)
      .replace(/\\/g, "/")
      .replace(/\.tsx$/, "");

    const segments = relative.split("/");
    const fileName = segments.pop() ?? "";
    const pathSegments = [...segments];

    if (fileName !== "index") {
      // TanStack 扁平文件名：edit.$id -> edit/$id
      const flatSegments = fileName.split(".").filter(Boolean);
      pathSegments.push(...flatSegments);
    }

    const visibleSegments = pathSegments.filter(
      (segment) => !segment.startsWith("_"),
    );

    const routePath =
      visibleSegments.length === 0 ? "/" : `/${visibleSegments.join("/")}`;
    paths.add(routePath);
  }

  return [...paths].sort();
}

export function buildRegexDefinitions(paths: Array<string>): Array<string> {
  return paths.map((routePath) => {
    let patternStr = "";
    if (routePath === "/") {
      patternStr = "^/$";
    } else {
      let pattern = routePath.replace(/[.*+?^()|[\]\\]/g, "\\$&");
      pattern = pattern.replace(/\$[^/]+/g, "[^/]+");
      patternStr = `^${pattern}/?$`;
    }

    const literalPattern = patternStr
      .replace(/\//g, "\\/")
      .replace(/\[\^\\\/\]\+/g, "[^/]+");

    return `/${literalPattern}/`;
  });
}

export function buildManifestContent(paths: Array<string>): string {
  const regexDefinitions = buildRegexDefinitions(paths);

  return `// Automatically generated by scripts/generate-manifest.ts
// Do not edit this file manually.

// Pre-compiled Regexes for maximum performance on Cloudflare Workers
export const ROUTE_REGEXPS: Array<RegExp> = [
  ${regexDefinitions.join(",\n  ")},
];

/**
 * Checks if the path matches any valid route.
 * O(n) regex checks, but zero compilation overhead at runtime.
 */
export function isPathValid(path: string): boolean {
  return ROUTE_REGEXPS.some((regex) => regex.test(path));
}
`;
}

function main() {
  const paths = collectRoutePaths(routesDir);
  const content = buildManifestContent(paths);
  fs.writeFileSync(outputPath, content);
  console.log(
    `✅ Generated manifest with ${paths.length} routes to ${outputPath}`,
  );
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  main();
}
